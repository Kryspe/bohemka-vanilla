CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- 1. USERS
CREATE TABLE IF NOT EXISTS users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    username TEXT UNIQUE NOT NULL,
    password_hash TEXT,
    name TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'plavec',
    year_of_birth INT,
    club_category TEXT,
    email TEXT,
    phone TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. NEWS
CREATE TABLE IF NOT EXISTS news (
    id TEXT PRIMARY KEY,
    slug TEXT,
    title TEXT NOT NULL,
    author TEXT,
    date DATE NOT NULL,
    excerpt TEXT,
    body JSONB DEFAULT '[]'::jsonb,
    image_url TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. EVENTS
CREATE TABLE IF NOT EXISTS events (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    place TEXT,
    date DATE NOT NULL,
    deadline DATE,
    type TEXT,
    kind TEXT DEFAULT 'zavod',
    status TEXT DEFAULT 'open',
    disciplines JSONB DEFAULT '[]'::jsonb,
    note TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. EVENT ENTRIES (Signups)
CREATE TABLE IF NOT EXISTS event_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id TEXT NOT NULL,
    user_id TEXT,
    swimmer_name TEXT NOT NULL,
    group_name TEXT,
    disciplines JSONB DEFAULT '[]'::jsonb,
    note TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. PARENT MESSAGES
CREATE TABLE IF NOT EXISTS parent_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category TEXT,
    title TEXT,
    text TEXT NOT NULL,
    date TEXT,
    author TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. TRAINERS
CREATE TABLE IF NOT EXISTS trainers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    role TEXT,
    email TEXT,
    phone TEXT,
    bio TEXT,
    photo_url TEXT,
    sort_order INT DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. YEARBOOKS
CREATE TABLE IF NOT EXISTS yearbooks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    year INT NOT NULL,
    title TEXT NOT NULL,
    file_url TEXT NOT NULL,
    file_size TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 8. RECORDS
CREATE TABLE IF NOT EXISTS records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pool TEXT NOT NULL,
    gender TEXT NOT NULL,
    event TEXT NOT NULL,
    time TEXT NOT NULL,
    swimmer_name TEXT NOT NULL,
    year TEXT,
    note TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

